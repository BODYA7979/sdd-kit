log(`QAPlan: ${(qa && qa.testCases || []).length} case(s)${qa && qa.path ? ` → ${qa.path}` : ''} | Docs: ${(docs && docs.updatedDocs || []).length} updated, ${(docs && docs.newDocs || []).length} new`)

// --- Grade (acceptance gate: verify artifacts against the actual code) ---
phase('Grade')
const grade = await runAgent(
  `Act as a strict Verifier. Score the QA plan and docs against the ACTUAL in-scope code. Read the code — do not trust the artifacts.
Scope: ${scopeDesc}
Acceptance criteria: ${JSON.stringify(criteriaList)}
QA coverage: ${JSON.stringify(qa && qa.coverage)}
QA cases: ${JSON.stringify((qa && qa.testCases || []).map((t) => ({ title: t.title, covers: t.coversCriterion, files: t.contributingFiles })))}
Docs updated: ${JSON.stringify((docs && docs.updatedDocs || []).concat(docs && docs.newDocs || []))}

Score 0-100: completeness (every criterion + feature covered), helpfulness (a human could actually use these), truthfulness (claims match code). phantomLinks = any doc/test claim that does NOT resolve to real code. uncoveredCriteria = acceptance criteria with no covering test. verdict = CHANGES_REQUIRED if any phantom link OR any uncovered criterion OR truthfulness < 80, else PASS.`,
  { phase: 'Grade', schema: GRADE_SCHEMA, agentType: 'outcomes-grader', ...MODELS.grade }
)
log(`Grade: ${grade ? grade.verdict : '?'} (T:${grade ? grade.truthfulness : '?'})${grade && (grade.uncoveredCriteria || []).length ? ` — ${grade.uncoveredCriteria.length} uncovered` : ''}${grade && (grade.phantomLinks || []).length ? `, ${grade.phantomLinks.length} phantom link(s)` : ''}`)

// --- Report -------------------------------------------------------------
phase('Report')
const report = await runAgent(
  `Write a concise markdown report. Sections: Summary, Scope, Stack & repos (flag untracked/WIP), Features documented, Acceptance criteria (source: ${criteria ? criteria.source : '?'}; note any needing human validation), Coverage matrix (criterion → covering tests, mark gaps), QA plan location, Documentation updated/new, Grade (completeness/helpfulness/truthfulness + phantom links + uncovered criteria), Recommendation (PASS = ready for human review; CHANGES_REQUIRED = list what to fix). AI output is a strong draft — the human is the final gate.
Scope: ${scopeDesc}
Repo warnings: ${JSON.stringify(repoWarnings)}
Criteria: ${JSON.stringify(criteria)}
QA: ${JSON.stringify({ path: qa && qa.path, coverage: qa && qa.coverage })}
Docs: ${JSON.stringify(docs)}
Grade: ${JSON.stringify(grade)}`,
  { phase: 'Report', ...MODELS.report }
)

return {
  scope: scopeDesc,
  features: codeIndex.features.map((f) => f.name),
  criteriaCount: criteriaList.length,
  qaPlanPath: qa ? qa.path || null : null,
  coverage: qa ? qa.coverage || [] : [],
  docsUpdated: docs ? (docs.updatedDocs || []).concat(docs.newDocs || []) : [],
  grade: grade ? grade.verdict : null,
  gradeDetail: grade,
  repoWarnings,
  report,
}
