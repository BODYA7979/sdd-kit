// --- Build (serial; right specialist + repo per task; budget-guarded) ----
const built = []
const failedTasks = []
async function buildTasks(list) {
  for (const task of list) {
    if (budget.total && budget.remaining() < 80_000) {
      log(`Budget low (${Math.round(budget.remaining() / 1000)}k left) — stopping build at task ${task.id}.`)
      list.filter((t) => t.id >= task.id).forEach((t) => failedTasks.push(t.id))
      break
    }
    const repo = repoForStack(task.stack)
    const priorContext = built.length ? `Already completed: ${built.map((b) => b.summary).join('; ')}` : 'This is the first task.'
    // write-spec makes task 1 of a refactor spec the characterization task.
    const characterization = specType === 'refactor' && (task.id === 1 || /characteri[sz]ation/i.test(task.title || ''))
    const method = specType !== 'refactor'
      ? 'using TDD (failing test first, then make it pass)'
      : characterization
        ? 'as the characterization task of a behavior-preserving refactor: write tests that pin TODAY\'s behavior for each MNC item it covers and run them against the unchanged code — they must PASS (green first, no RED step). A characterization test that fails means the code does not do what the MNC item says: stop, set completed=false, and report the mismatch. Change no production code in this task'
        : 'as a step of a behavior-preserving refactor: there is no RED step. Restructure the code with the characterization (MNC guard) tests green before and after, and never edit them. A structural AC (e.g. "X has no pricing logic") may get an architecture test, which fails first as usual'
    const result = await runAgent(
      `Implement this task ${method}. Work in the ${repo.role} repo (${repo.stack}) at "${repo.path}" — cd there.
Task ${task.id}: ${task.title}
Approach: ${task.approach || '(derive from the spec and surrounding code)'}
${task.verify ? `Verify: ${task.verify}` : ''}
${(task.covers || []).length ? `Covers: ${task.covers.join(', ')} — name the test after the criterion so the tasks.md Traceability row can point at it.` : ''}
${task.files && task.files.length ? `Likely files: ${task.files.join(', ')}` : ''}
${priorContext}
${mustNotChange.length ? `Must NOT change (keep identical; do not edit their guard tests): ${mustNotChange.join('; ')}` : ''}
${nfrs.length ? `Quality attributes (an NFR this task covers is built against like an AC: a test per role for authorization, a measured check for a latency budget, an axe assertion for accessibility): ${nfrs.join('; ')}` : ''}

Conventions: ${(repo.conventions || invConventions).join('; ') || 'match surrounding style'}
Standards: no changelog/AI-marker comments, lowercase doc filenames, match surrounding style.
${specTrackNote}
Set completed=true only if the task is fully done with a passing test. Return what you changed (full repo-relative paths).`,
      { label: `build:t${task.id}`, phase: 'Build', schema: BUILD_SCHEMA, agentType: agentForStack(task.stack), ...MODELS.build }
    )
    if (result && result.completed !== false) built.push({ id: task.id, ...result })
    else failedTasks.push(task.id)
  }
}

