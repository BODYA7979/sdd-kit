phase('Gates')
function gateInstructionsFor(t) {
  const cmds = (gateCommandsByRepo[t.path] || []).map((g) => `- ${g.name}: ${g.command}`).join('\n')
  return `Run the quality gates for the ${t.role} repo (${t.stack}) at "${t.path}". cd there.
Gates (run each; tool genuinely absent => "skip"; tool present but cannot run => "unreachable", NEVER "pass"):
${cmds || '- (run the stack lint + test tooling that the scaffold configured)'}
- Build check: confirm the scaffold itself builds/boots (e.g. the app starts, the test suite collects).
- Debug scan: grep for stray ${debugScanFor(t.stack)} outside tests -> fail if found.
Report each gate pass/fail/skip/unreachable with output in details; allPassed=true only if every gate is pass or skip; repo="${t.path}". Do not fix here.`
}
async function runGates() {
  const list = sliceReposOrdered.length ? sliceReposOrdered : targets
  const results = (await parallel(list.map((t) => () => runAgent(gateInstructionsFor(t), { label: `gates:${t.role}`, phase: 'Gates', schema: GATES_SCHEMA, ...MODELS.gatesFix })))).filter(Boolean)
  const allGates = results.flatMap((g) => (g.gates || []).map((x) => ({ ...x, repo: g.repo })))
  return { results, allGates, allPassed: results.length > 0 && results.every((g) => g.allPassed) }
}
let gates = await runGates()
let fixRounds = 0
while (!gates.allPassed && fixRounds < 3) {
  const failing = gates.allGates.filter((g) => g.status === 'fail' || g.status === 'unreachable')
  if (!failing.length) { log('Gates not all green but nothing actionable — stopping.'); break }
  if (budget.total && budget.remaining() < 60_000) { log(`Budget low — stopping gate fixes.`); break }
  fixRounds++
  log(`Gates round ${fixRounds}: fixing ${failing.length} failing gate(s)`)
  const list = (sliceReposOrdered.length ? sliceReposOrdered : targets)
  await parallel(
    list.filter((t) => failing.some((f) => !f.repo || f.repo === t.path)).map((t) => () =>
      runAgent(
        `Quality gates are failing in the ${t.role} repo (${t.stack}) at "${t.path}". cd there. Fix the underlying code/config (not by suppressing errors or weakening tests).
Failures:
${failing.filter((f) => !f.repo || f.repo === t.path).map((g) => `- ${g.name}: ${g.details || ''}`).join('\n')}`,
        { label: `gates:fix${fixRounds}:${t.role}`, phase: 'Gates', agentType: agentForStack(t.stack), ...MODELS.gatesFix }
      )
    )
  )
  gates = await runGates()
}

