const entryPoints = (repro && repro.entryPoints) || []
const perf = repro && repro.performance && repro.performance.baseline ? repro.performance : null
log(`Reproduce: ${reproduced ? 'reproduced' : 'NOT reproduced'}${repro && repro.observedFailure ? ` — ${String(repro.observedFailure).slice(0, 80)}` : ''}${perf ? ` (baseline ${perf.baseline}, target ${perf.target || 'unset'})` : ''}`)

if (!reproduced) {
  phase('Report')
  const needInfo = await runAgent(
    `Write a short markdown report: the bug could NOT be reproduced. State the bug, the reproduction steps attempted, and exactly what information or access is needed from the reporter to proceed. Recommendation: NEEDS-INFO.
Bug: ${bug}
Attempted: ${JSON.stringify(repro)}`,
    { phase: 'Report', ...MODELS.report }
  )
  return { bug, reproduced: false, recommendation: 'NEEDS-INFO', repoWarnings, report: needInfo }
}

// --- RootCause ----------------------------------------------------------
phase('RootCause')
const rootCause = await runAgent(
  `Localize the defect to specific code and explain the mechanism. cd into the relevant repo. Read the actual code in the failing path.
Bug: ${bug}
Observed failure: ${repro.observedFailure || ''}
Repro steps: ${(repro.steps || []).join(' → ')}

Trace from the entry point to the failure. Identify the precise file(s) + line(s) responsible and the mechanism (the "why" — the wrong condition, missing branch, off-by-one, bad state). Propose a minimal fix approach that addresses the cause, not the symptom. Tag each location with its repo path.
List mustNotChange: existing, currently-correct behavior that runs through the same code (other callers, sibling branches, response shapes, permissions) and must remain identical after the fix — concrete and checkable, e.g. "card-order refunds still require approval".${callerMustNotChange.length ? `
The reporter already listed: ${JSON.stringify(callerMustNotChange)} — keep those and add only what they missed.` : ''}`,
  { phase: 'RootCause', schema: ROOTCAUSE_SCHEMA, agentType: 'code-explorer', ...MODELS.rootcause }
)

// Adversarially verify the hypothesis before writing any code (refute-by-default).
const rcVotes = (rootCause
  ? (await parallel(
      ['correctness', 'evidence', 'completeness'].map((lens) => () =>
        runAgent(
          `A root-cause hypothesis for this bug: mechanism "${rootCause.mechanism}" at ${(rootCause.locations || []).map((l) => `${l.file}${l.line ? ':' + l.line : ''}`).join(', ')}.
Bug: ${bug}. Observed: ${repro.observedFailure || ''}.
Judge through the ${lens} lens against the ACTUAL code. Try to REFUTE it — would this really produce the observed failure? default real=false if you cannot confirm it from the code.`,
          { label: `verify:rootcause`, phase: 'RootCause', schema: VERDICT_SCHEMA, ...MODELS.verify }
        )
      )
    )).filter(Boolean)
  : [])
const rcYes = rcVotes.filter((v) => v.real).length
const rcConfirmed = !!(rootCause && rootCause.confirmed) && rcVotes.length > 0 && rcYes >= Math.ceil(rcVotes.length / 2)
log(`RootCause: ${rcConfirmed ? 'confirmed' : 'UNCONFIRMED'} (${rcYes}/${rcVotes.length} votes) — ${rootCause ? String(rootCause.mechanism).slice(0, 80) : 'none'}`)

const mustNotChange = Array.from(new Set([...callerMustNotChange, ...((rootCause && rootCause.mustNotChange) || [])]))
if (mustNotChange.length) log(`Must NOT change: ${mustNotChange.length} behavior(s) guarded`)

const fixRepo = ((rootCause && rootCause.locations) || []).map((l) => repos.find((r) => r.path === l.repo)).find(Boolean) || primaryRepo

// --- RegressionTest -----------------------------------------------------
phase('RegressionTest')
const regression = await runAgent(
  `Write a FAILING regression test that reproduces this bug, then confirm it fails for the right reason. Work in the ${fixRepo.role} repo (${fixRepo.stack}) at "${fixRepo.path}" — cd there.
Bug: ${bug}
Reproduction: ${(repro.steps || []).join(' → ')}
Expected behavior: ${repro.expectedBehavior || rootCause && rootCause.mechanism || ''}

1. Add a test asserting the EXPECTED (correct) behavior — it must currently FAIL because of the bug.${perf ? `
   This is a slowness bug (baseline ${perf.baseline}, target ${perf.target || 'unset'}): assert the cause, not wall-clock time — a query-count ceiling for the request, eager loading of the relation, the index being used — so the test is deterministic.` : ''}
2. Run it and confirm it is red, and red for the bug's reason (not a setup error).
${mustNotChange.length ? `3. Guard tests — for each behavior below, find an existing test that pins it or write one; each must be GREEN now (it documents behavior that must survive the fix):
${mustNotChange.map((m, i) => `   MNC-${i + 1}: ${m}`).join('\n')}
4.` : '3.'} Commit the failing test${mustNotChange.length ? ' and the guard tests' : ''} as a checkpoint (git add the test files + commit with a plain message; no AI-marker comments).
Conventions: ${(fixRepo.conventions || []).join('; ') || 'match surrounding test style'}. Return the test file path(s) in changedFiles and completed=true only if the test is red for the right reason.`,
  { label: 'regression', phase: 'RegressionTest', schema: BUILD_SCHEMA, agentType: agentForStack(fixRepo.stack), ...MODELS.regression }
)
const regressionFiles = (regression && regression.changedFiles) || []
log(`RegressionTest: ${regression && regression.completed ? 'red as expected' : 'could not establish a failing test'}`)

// --- Fix ----------------------------------------------------------------
phase('Fix')
const fix = await runAgent(
  `Make the minimal change that fixes the root cause and turns the regression test green. Work in the ${fixRepo.role} repo (${fixRepo.stack}) at "${fixRepo.path}" — cd there.
Bug: ${bug}
Root cause: ${rootCause ? rootCause.mechanism : '(derive from the failing test)'}
Fix approach: ${rootCause ? rootCause.fixApproach : ''}
Locations: ${(rootCause && rootCause.locations || []).map((l) => `${l.file}${l.line ? ':' + l.line : ''}`).join(', ') || '(localize from the test)'}
Regression test (DO NOT EDIT — it is the oracle): ${regressionFiles.join(', ')}
${mustNotChange.length ? `Must NOT change (their guard tests are equally immutable and must stay green): ${mustNotChange.join('; ')}` : ''}

Change only what is needed to address the cause. You are FORBIDDEN from editing the regression test or guard tests, or weakening any assertion. Run the test; it must pass. Run the broader suite for the touched area to catch neighbors. Standards: no changelog/AI-marker comments, match surrounding style. Return changed files (full repo-relative paths); completed=true only if the regression test passes without modifying it.`,
  { label: 'fix', phase: 'Fix', schema: BUILD_SCHEMA, agentType: agentForStack(fixRepo.stack), ...MODELS.fix }
)
const changedFiles = Array.from(new Set([...(regressionFiles), ...((fix && fix.changedFiles) || [])]))
const fixApplied = !!(fix && fix.completed)
log(`Fix: ${fixApplied ? 'regression test green' : 'NOT green'} — ${changedFiles.length} file(s) touched`)

// --- Gates --------------------------------------------------------------
phase('Gates')
async function runGates() {
  const results = (await parallel(repos.map((r) => () => runAgent(gateInstructionsFor(r), { label: `gates:${r.role}`, phase: 'Gates', schema: GATES_SCHEMA, ...MODELS.gatesFix })))).filter(Boolean)
  const allGates = results.flatMap((g) => (g.gates || []).map((x) => ({ ...x, repo: g.repo })))
  return { results, allGates, allPassed: results.length > 0 && results.every((g) => g.allPassed) }
}
let gates = await runGates()
let fixRounds = 0
while (!gates.allPassed && fixRounds < 3) {
  const failing = gates.allGates.filter((g) => g.status === 'fail' || g.status === 'unreachable')
  if (!failing.length) {
    log('Gates not all green but nothing actionable — stopping loop.')
    break
  }
  if (budget.total && budget.remaining() < 60_000) {
    log(`Gates failing but budget low (${Math.round(budget.remaining() / 1000)}k left) — stopping fix loop.`)
    break
  }
  fixRounds++
  log(`Gates round ${fixRounds}: fixing ${failing.length} failing gate(s)`)
  const byRepo = repos.filter((r) => failing.some((f) => f.repo === r.path))
  await parallel(
    (byRepo.length ? byRepo : repos).map((r) => () =>
      runAgent(
        `Quality gates are failing in the ${r.role} repo (${r.stack}) at "${r.path}". cd there. Fix the underlying code (not the gate config, not the regression or guard tests); do not suppress errors or weaken assertions.
Failures:
${failing.filter((f) => !f.repo || f.repo === r.path).map((g) => `- ${g.name}: ${g.details || ''}`).join('\n')}`,
        { label: `gates:fix${fixRounds}:${r.role}`, phase: 'Gates', agentType: agentForStack(r.stack), ...MODELS.gatesFix }
      )
    )
  )
  gates = await runGates()
}

// --- Acceptance ---------------------------------------------------------
phase('Acceptance')
let acceptance = null
if (!fixApplied) {
  log('Acceptance: skipped — no working fix to verify.')
} else {
  acceptance = await runAgent(
    `Verify the ORIGINAL reported bug is actually gone end-to-end against the code as it stands. Do NOT trust that the regression test passing means the user-facing symptom is fixed — re-walk the real scenario.
Bug: ${bug}
Repos: ${JSON.stringify(repos.map((r) => ({ role: r.role, stack: r.stack, path: r.path, tracked: r.tracked })))}
Entry points: ${entryPoints.join(', ') || '(derive from the bug description)'}
Original failure: ${repro.observedFailure || ''}
Expected: ${repro.expectedBehavior || ''}
Changed files: ${changedFiles.join(', ')}

Must NOT change: ${JSON.stringify(mustNotChange)}

From each entry point, follow every hop to the expected end state. Record step/expected/actual/ok. A redirect or link whose target does not resolve is ok=false (brokenLinks).
For each Must NOT change behavior, re-walk it and record it in unchanged (behavior, ok, evidence — guard test result or the hop you traced); compare with \`git diff\` of the fix so an incidental change is caught.
${perf ? `This is a slowness report. Re-measure with the same command (${perf.command || 'as in Reproduce'}) and record it as a step: baseline ${perf.baseline}, target ${perf.target || '(none set)'}, actual now. The symptom is gone only when the target is met.
` : ''}Set resolved=true ONLY if the original symptom no longer occurs, the full journey reaches the expected end state, and every unchanged entry is ok. If a repo is untracked WIP, note it in reason.`,
    { phase: 'Acceptance', schema: ACCEPTANCE_SCHEMA, ...MODELS.acceptance }
  )
  if (acceptance) log(`Acceptance: ${acceptance.resolved ? 'RESOLVED' : 'NOT resolved'}${(acceptance.brokenLinks || []).length ? ` — broken: ${acceptance.brokenLinks.join(', ')}` : ''}`)
}
const acceptanceResolved = !!(acceptance && acceptance.resolved)

// --- Report -------------------------------------------------------------
phase('Report')
const testPlan = await runAgent(
  `Write a short copy-paste manual test plan a human runs to confirm this bug is fixed by hand — real values, no jargon. Verify each step against the actual code.
Bug: ${bug}
Entry points: ${entryPoints.join(', ') || '(from the bug description)'}
App URL: ${devUrl}
Each step: an exact action (URL/command/click with example data) + the exact expected result. Cover the originally-failing case (it must now pass) and ${mustNotChange.length ? `each Must NOT change behavior (it must behave exactly as before): ${mustNotChange.join('; ')}` : 'one neighbor that must still work'}.
${primaryRepo && primaryRepo.path ? `Optionally write the plan to a file near the repo if a docs/ or .ai/ folder exists; otherwise return steps inline.` : ''}`,
  { phase: 'Report', schema: TEST_PLAN_SCHEMA, ...MODELS.verify }
)

const verdict = !reproduced ? 'NEEDS-INFO' : (!fixApplied || !gates.allPassed || !acceptanceResolved || repoWarnings.length) ? 'NOT-RESOLVED' : 'FIXED'
const report = await runAgent(
  `Write a concise markdown bug-fix report. Sections: Summary, Stack & repos (flag any untracked/WIP repo), Reproduction (steps + observed failure), Root cause (mechanism + file:line, confirmed by ${rcYes}/${rcVotes.length} verify votes), Regression test (path, red→green), Fix (what changed + files), Must NOT change (each behavior + guard + still identical?), Quality gates per repo (pass/fail/skip/unreachable), Acceptance (did the ORIGINAL symptom disappear end-to-end?${perf ? ' For this slowness report: the re-measured value against the baseline and the target, with the same command — FIXED requires the target met.' : ''}), Manual test plan (how to verify by hand), Prevention, Recommendation (${verdict} — never FIXED unless the regression test is green AND acceptance resolved AND gates pass), Next.
Prevention (proposed only — change nothing): name the CLASS of this bug in one line (for example "authorization checked in the UI but not in the Server Action", "N+1 query in an API resource", "nullable column read without a guard"), then the cheapest guard that would have caught the whole class, in this order of preference: an architecture or regression test (Pest arch / Vitest), a static rule (PHPStan, ESLint), a path-scoped rule line in .claude/rules/, a GOTCHA or invariant line in CLAUDE.md, or a hook (proposal text only). Give the exact location and the one-line rule. End the section with: "Run /learn with this Prevention item to add the guard."
Next (only when the verdict is FIXED): "/open-pr --report=<reportPath>", then "/learn <the Prevention item>".
Save the report: in the repo at "${(primaryRepo && primaryRepo.path) || '.'}", mkdir -p .ai/reports and write it to .ai/reports/fix-${ticket || '<slug>'}-$(date +%Y%m%d-%H%M).md${ticket ? '' : ' (<slug> = 2-5 lowercase-hyphenated words naming the symptom)'}, taking the timestamp from the shell, never inventing it. Lowercase filename, written as a human maintainer, no AI-marker comments. Return reportPath (the path relative to the current directory, the same path the Next line names) and markdown (the full report).
Bug: ${bug}
Repo warnings: ${JSON.stringify(repoWarnings)}
Reproduce: ${JSON.stringify(repro)}
RootCause: ${JSON.stringify(rootCause)} (confirmed=${rcConfirmed})
Regression: ${JSON.stringify(regression)}
Fix: ${JSON.stringify(fix)}
Gates: ${JSON.stringify(gates.allGates)}
Must NOT change: ${JSON.stringify(mustNotChange)}
Performance: ${JSON.stringify(perf)}
Acceptance: ${JSON.stringify(acceptance)}
Manual test plan: ${JSON.stringify(testPlan)}`,
  { phase: 'Report', schema: REPORT_SCHEMA, ...MODELS.report }
)
const reportPath = (report && report.reportPath) || null
if (reportPath) log(`Report saved: ${reportPath}`)

return {
  bug,
  reproduced,
  rootCauseConfirmed: rcConfirmed,
  changedFiles,
  gatesPassed: gates ? gates.allPassed : false,
  acceptanceResolved,
  acceptance,
  mustNotChange,
  repoWarnings,
  performance: perf,
  recommendation: verdict,
  next: verdict === 'FIXED' ? [`/open-pr --report=${reportPath || '<save the report to a file first>'}`, '/learn <Prevention item>'] : [],
  manualTestPlan: testPlan ? testPlan.path || testPlan : null,
  reportPath,
  report: report ? report.markdown : null,
}
