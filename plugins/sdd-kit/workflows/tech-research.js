if (adr && adr.path) log(`ADR: ${adr.path}`)

// --- Report -------------------------------------------------------------
phase('Report')
const report = await runAgent(
  `Write a concise markdown report. Sections: Summary, Decision question, Stack context, Options compared (scores + one-line pro/con each), Recommendation + confidence, Runner-up + why not, Disagreement flags, Open questions for the human, Dropped (unverified) claims that did NOT inform the decision, ADR location. This is a recommendation for human sign-off — make the open questions and confidence prominent.
Question: ${question}
Decision: ${JSON.stringify(decision)}
Dropped claims: ${JSON.stringify(dropped.map((c) => ({ option: c.option, insight: c.insight })))}
ADR: ${JSON.stringify(adr)}`,
  { phase: 'Report', ...MODELS.report }
)

return {
  question,
  options,
  recommendation: decision ? decision.recommendation : null,
  runnerUp: decision ? decision.runnerUp : null,
  confidence: decision ? decision.confidence : null,
  disagreementFlags: decision ? decision.disagreementFlags || [] : [],
  openQuestions: decision ? decision.openQuestions || [] : [],
  droppedClaims: dropped.length,
  adrPath: adr ? adr.path || null : null,
  report,
}
